//! Which name servers to ask: the ones typed, or the ones this machine uses.

use anyhow::{Context, bail};
use std::net::{IpAddr, SocketAddr, ToSocketAddrs};

#[derive(Clone)]
pub struct Server {
    pub address: SocketAddr,
    /// `system`, the name typed, or the name of the domain's own name server.
    pub name: Option<String>,
}

impl Server {
    /// `system (192.168.1.1)`, `dns.google (8.8.8.8)`, or the address alone; the port only when
    /// it isn't 53.
    pub fn label(&self) -> String {
        let address = match self.address.port() {
            53 => self.address.ip().to_string(),
            _ => self.address.to_string(),
        };
        match &self.name {
            Some(name) => format!("{name} ({address})"),
            None => address,
        }
    }
}

/// The servers typed (an address, an address and port, or a name), or else the first one this
/// machine uses.
pub fn choose(typed: &[String]) -> anyhow::Result<Vec<Server>> {
    if typed.is_empty() {
        let Some(&ip) = system().first() else {
            bail!("this machine has no name server set; give one, like --server 1.1.1.1");
        };
        return Ok(vec![Server {
            address: SocketAddr::new(ip, 53),
            name: Some("system".to_string()),
        }]);
    }
    typed.iter().map(|text| typed_server(text)).collect()
}

fn typed_server(text: &str) -> anyhow::Result<Server> {
    if let Ok(ip) = text.parse::<IpAddr>() {
        return Ok(Server {
            address: SocketAddr::new(ip, 53),
            name: None,
        });
    }
    if let Ok(address) = text.parse() {
        return Ok(Server {
            address,
            name: None,
        });
    }
    let found: Vec<SocketAddr> = (text, 53)
        .to_socket_addrs()
        .with_context(|| format!("{text} is not an address, and no name server knows it"))?
        .collect();
    let address = found
        .iter()
        .find(|address| address.is_ipv4())
        .or(found.first());
    Ok(Server {
        address: *address.context(format!("{text} has no address"))?,
        name: Some(text.to_string()),
    })
}

/// The name servers this machine asks, from the adapters' settings (GetNetworkParams).
#[cfg(windows)]
fn system() -> Vec<IpAddr> {
    use windows_sys::Win32::NetworkManagement::IpHelper::{
        FIXED_INFO_W2KSP1, GetNetworkParams, IP_ADDR_STRING,
    };
    let mut size = 0u32;
    // The first call only says how big the answer is. SAFETY: a null buffer is how to ask.
    unsafe { GetNetworkParams(std::ptr::null_mut(), &mut size) };
    // u64s, so the buffer is aligned for the pointers in the answer.
    let mut buffer = vec![0u64; (size as usize).div_ceil(8)];
    let info = buffer.as_mut_ptr().cast::<FIXED_INFO_W2KSP1>();
    // SAFETY: the buffer is the size Windows asked for and lives until the end of the function.
    if unsafe { GetNetworkParams(info, &mut size) } != 0 {
        return Vec::new();
    }
    let mut servers = Vec::new();
    // SAFETY: Windows filled in the list; each entry points into the buffer, the last at null.
    let mut entry: *const IP_ADDR_STRING = unsafe { &(*info).DnsServerList };
    while let Some(server) = unsafe { entry.as_ref() } {
        let text: Vec<u8> = server.IpAddress.String.iter().map(|&c| c as u8).collect();
        let text = String::from_utf8_lossy(&text);
        if let Ok(ip) = text.trim_end_matches('\0').parse() {
            servers.push(ip);
        }
        entry = server.Next;
    }
    servers
}

/// Linux and macOS both keep the name servers in /etc/resolv.conf (on Linux with
/// systemd-resolved, its own stub at 127.0.0.53; on macOS, written from the network settings).
#[cfg(not(windows))]
fn system() -> Vec<IpAddr> {
    resolv_conf(&std::fs::read_to_string("/etc/resolv.conf").unwrap_or_default())
}

/// The `nameserver` lines of resolv.conf, without a link-local address's `%en0`.
#[cfg_attr(windows, allow(dead_code))]
fn resolv_conf(text: &str) -> Vec<IpAddr> {
    text.lines()
        .filter_map(|line| line.trim().strip_prefix("nameserver"))
        .filter_map(|address| address.trim().split('%').next()?.parse().ok())
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn reads_resolv_conf() {
        let text = "# Generated by NetworkManager\nsearch lan\nnameserver 192.168.1.1\n\
                    nameserver fe80::1%en0\n  nameserver 1.1.1.1\noptions edns0\n";
        let servers: Vec<String> = resolv_conf(text).iter().map(IpAddr::to_string).collect();
        assert_eq!(servers, ["192.168.1.1", "fe80::1", "1.1.1.1"]);
    }

    #[test]
    fn takes_an_address_and_a_port() {
        let servers = choose(&["1.1.1.1".to_string(), "192.168.1.1:5353".to_string()]).unwrap();
        assert_eq!(servers[0].label(), "1.1.1.1");
        assert_eq!(servers[1].label(), "192.168.1.1:5353");
    }
}
